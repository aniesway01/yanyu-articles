#!/usr/bin/env python3
"""Build consolidated topic files from 惠琼保 articles"""
import sys, io, os, re, json
if sys.platform == 'win32':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

# Load all articles
articles = {}
for d in sorted(os.listdir('.')):
    if not os.path.isdir(d) or not d[0].isdigit():
        continue
    txt = os.path.join(d, 'article.txt')
    if not os.path.exists(txt) or os.path.getsize(txt) < 50:
        continue
    with open(txt, 'r', encoding='utf-8') as f:
        content = f.read()
    url_m = re.search(r'(?:来源URL|链接):\s*(https?://\S+)', content)
    title_m = re.search(r'标题:\s*(.+)', content)
    sep_idx = content.find('=' * 10)
    body = content[sep_idx:].split('\n', 1)[1].strip() if sep_idx > 0 else content
    articles[d] = {
        'title': title_m.group(1).strip() if title_m else d,
        'url': url_m.group(1).strip() if url_m else '',
        'body': body, 'size': len(body),
    }

sub = os.path.join('.', '手动补充文章')
if os.path.isdir(sub):
    for d in sorted(os.listdir(sub)):
        dp = os.path.join(sub, d)
        if not os.path.isdir(dp): continue
        txt = os.path.join(dp, 'article.txt')
        if not os.path.exists(txt): continue
        with open(txt, 'r', encoding='utf-8') as f:
            content = f.read()
        url_m = re.search(r'(?:来源URL|链接):\s*(https?://\S+)', content)
        title_m = re.search(r'标题:\s*(.+)', content)
        sep_idx = content.find('=' * 10)
        body = content[sep_idx:].split('\n', 1)[1].strip() if sep_idx > 0 else content
        key = f'{sub}/{d}'
        articles[key] = {
            'title': title_m.group(1).strip() if title_m else d,
            'url': url_m.group(1).strip() if url_m else '',
            'body': body, 'size': len(body),
        }

print(f'Loaded {len(articles)} articles')


def ref(key_fragment):
    for k, a in articles.items():
        if key_fragment in k:
            if a['url']:
                return f'> 来源: [{a["title"]}]({a["url"]})'
            return f'> 来源: {a["title"]}'
    return f'> 来源: {key_fragment}'


